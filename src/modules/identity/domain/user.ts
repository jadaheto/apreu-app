import { Entity, type EntityId } from '../../../shared/domain/entity.js';
import { Guard } from '../../../shared/domain/guard.js';
import { ALL_ROLES, type Role } from '../../../shared/domain/role.js';
import { Email } from '../../../shared/domain/value-objects/email.vo.js';

export interface UserProps {
  name: string;
  email: Email;
  passwordHash: string;
  role: Role;
  avatar: string | null;
  isActive: boolean;
  lastLogin: Date | null;
  createdAt: Date | null;
  /** True while the user signs in with a temporary password assigned by an administrator. */
  mustChangePassword: boolean;
}

export interface CreateUserProps {
  name: string;
  email: string;
  passwordHash: string;
  role: Role;
  avatar?: string | null;
  /** Set when the initial password is a temporary one generated for the user. */
  mustChangePassword?: boolean;
}

/**
 * A person who can sign in to a school (`users` table).
 * Staff, students and guardians are all users distinguished by {@link Role}.
 */
export class User extends Entity<UserProps> {
  private constructor(id: EntityId, props: UserProps) {
    super(id, props);
  }

  static create(input: CreateUserProps): User {
    const name = input.name?.trim();
    Guard.againstEmpty(name, 'nombre');
    Guard.againstMaxLength(name, 150, 'nombre');
    Guard.againstEmpty(input.passwordHash, 'contraseña');
    Guard.oneOf(input.role, ALL_ROLES, 'rol');
    return new User(null, {
      name,
      email: Email.create(input.email),
      passwordHash: input.passwordHash,
      role: input.role,
      avatar: input.avatar ?? null,
      isActive: true,
      lastLogin: null,
      createdAt: null,
      mustChangePassword: input.mustChangePassword ?? false,
    });
  }

  /** Rebuilds a persisted user without re-running creation rules. */
  static restore(id: number, props: UserProps): User {
    return new User(id, { ...props });
  }

  get name(): string {
    return this.props.name;
  }
  get email(): Email {
    return this.props.email;
  }
  get passwordHash(): string {
    return this.props.passwordHash;
  }
  get role(): Role {
    return this.props.role;
  }
  get avatar(): string | null {
    return this.props.avatar;
  }
  get isActive(): boolean {
    return this.props.isActive;
  }
  get lastLogin(): Date | null {
    return this.props.lastLogin;
  }
  get createdAt(): Date | null {
    return this.props.createdAt;
  }
  get mustChangePassword(): boolean {
    return this.props.mustChangePassword;
  }

  recordLogin(at: Date): void {
    this.props.lastLogin = at;
  }

  /** Replaces the password chosen by the user; clears any pending forced change. */
  changePassword(newHash: string): void {
    Guard.againstEmpty(newHash, 'contraseña');
    this.props.passwordHash = newHash;
    this.props.mustChangePassword = false;
  }

  /**
   * Sets a temporary password generated by an administrator (creation or
   * reset). The user must replace it on the next sign-in (ADR-0005).
   */
  assignTemporaryPassword(temporaryHash: string): void {
    Guard.againstEmpty(temporaryHash, 'contraseña');
    this.props.passwordHash = temporaryHash;
    this.props.mustChangePassword = true;
  }

  rename(name: string): void {
    const trimmed = name?.trim();
    Guard.againstEmpty(trimmed, 'nombre');
    Guard.againstMaxLength(trimmed, 150, 'nombre');
    this.props.name = trimmed;
  }

  changeEmail(email: string): void {
    this.props.email = Email.create(email);
  }

  changeRole(role: Role): void {
    Guard.oneOf(role, ALL_ROLES, 'rol');
    this.props.role = role;
  }

  changeAvatar(avatar: string | null): void {
    this.props.avatar = avatar;
  }

  activate(): void {
    this.props.isActive = true;
  }

  deactivate(): void {
    this.props.isActive = false;
  }
}
