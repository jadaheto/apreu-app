export const MIN_MARKETING_CONTEXT = 10;
export const MAX_MARKETING_CONTEXT = 2000;

/** CRM figures sent to the generator (RN-COM-15). */
export interface CrmSnapshot {
  total_estudiantes_activos: number;
  fecha_actual: string;
}

export interface MarketingGenerationProps {
  userId: number;
  type: MarketingType;
  contextInput: string;
  crmData: Record<string, unknown>;
  aiResponse: string | null;
  createdAt: Date | null;
}

/**
 * Content generated by the marketing AI (`ai_marketing_campaigns`,
 * RN-COM-15). Visible only to its author.
 */
export class MarketingGeneration extends Entity<MarketingGenerationProps> {
  private constructor(id: EntityId, props: MarketingGenerationProps) {
    super(id, props);
  }

  /** Validates the generator request before calling the AI. */
  static assertValidRequest(type: MarketingType, context: string): string {
    Guard.oneOf(type, MARKETING_TYPES, 'tipo de campaña');
    const trimmed = context?.trim() ?? '';
    Guard.againstEmpty(trimmed, 'contexto');
    Guard.inRange(trimmed.length, MIN_MARKETING_CONTEXT, MAX_MARKETING_CONTEXT, 'longitud del contexto');
    return trimmed;
  }

  static record(
    input: { userId: number; type: MarketingType; contextInput: string; crmData: CrmSnapshot; aiResponse: string },
    at: Date,
  ): MarketingGeneration {
    return new MarketingGeneration(null, {
      userId: input.userId,
      type: input.type,
      contextInput: MarketingGeneration.assertValidRequest(input.type, input.contextInput),
      crmData: { ...input.crmData },
      aiResponse: input.aiResponse,
      createdAt: at,
    });
  }

  static restore(id: number, props: MarketingGenerationProps): MarketingGeneration {
    return new MarketingGeneration(id, { ...props });
  }

  get userId(): number {
    return this.props.userId;
  }
  get type(): MarketingType {
    return this.props.type;
  }
  get contextInput(): string {
    return this.props.contextInput;
  }
  get crmData(): Readonly<Record<string, unknown>> {
    return this.props.crmData;
  }
  get aiResponse(): string | null {
    return this.props.aiResponse;
  }
  get createdAt(): Date | null {
    return this.props.createdAt;
  }
}
